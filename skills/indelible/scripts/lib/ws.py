class Workspace(object):
    """The learner's study folder."""

    def __init__(self, root):
        self.root = Path(root).expanduser().resolve()
        self._config = None

    def __repr__(self):
        return "Workspace(%r)" % str(self.root)

    # ---- paths ------------------------------------------------------------
    @property
    def config_path(self):
        return self.root / CONFIG_NAME

    @property
    def claude_md(self):
        return self.root / "CLAUDE.md"

    @property
    def ledger_path(self):
        return self.root / "ledger.jsonl"

    @property
    def plan_dir(self):
        return self.root / "plan"

    @property
    def blocks_path(self):
        return self.root / "plan" / "blocks.jsonl"

    @property
    def ics_dir(self):
        return self.root / "plan" / "ics"

    @property
    def views_dir(self):
        return self.root / "views"

    @property
    def week_view_path(self):
        return self.root / "views" / "week.md"

    @property
    def reviews_dir(self):
        return self.root / "reviews"

    @property
    def inbox_dir(self):
        return self.root / "inbox"

    @property
    def archive_dir(self):
        return self.root / "archive"

    @property
    def state_dir(self):
        return self.root / ".indelible"

    @property
    def lock_path(self):
        return self.state_dir / "write.lock"

    @property
    def quarantine_path(self):
        return self.state_dir / "quarantine.jsonl"

    @property
    def render_state_path(self):
        return self.state_dir / "render.json"

    @property
    def backups_dir(self):
        return self.state_dir / "backups"

    def rel(self, path):
        """Workspace-relative POSIX path."""
        try:
            return Path(path).resolve().relative_to(self.root).as_posix()
        except ValueError:
            return Path(path).as_posix()

    def ensure_tree(self):
        for d in ROOT_DIRS:
            fio.ensure_dir(self.root / d)

    # ---- locking and reading ---------------------------------------------
    def lock(self, timeout=3.0):
        """The workspace write lock (a context manager)."""
        return fio.write_lock(self.root, timeout=timeout)

    def read_jsonl(self, path):
        return fio.read_jsonl(path, ws_root=self.root)

    def quarantine_rows(self):
        return fio.read_quarantine(self.root)

    def quarantine_count(self):
        return fio.quarantine_count(self.root)

    # ---- config -----------------------------------------------------------
    def load_config(self, reload=False):
        if self._config is None or reload:
            cfg = fio.read_json(self.config_path)
            if not isinstance(cfg, dict):
                raise DataError("%s is empty or not a JSON object" % self.config_path)
            self._config = cfg
        return self._config

    config = property(lambda self: self.load_config())

    def save_config(self, cfg):
        fio.write_json(self.config_path, cfg)
        self._config = cfg

    def timezone(self):
        return self.load_config().get("timezone")

    def tzinfo(self):
        """The workspace time zone (see ``dates.tz_for`` for the fallback)."""
        from lib import dates
        try:
            name = self.timezone()
        except (DataError, OSError):
            name = None
        return dates.tz_for(name)

    def now(self):
        """The current time in the workspace time zone: the one clock every command uses."""
        from lib import dates
        return dates.now().astimezone(self.tzinfo())

    def today(self):
        """Today's date in the workspace time zone."""
        return self.now().date()

    def schedule_mode(self):
        return (self.load_config().get("time") or {}).get("schedule", "scheduled")

    # ---- subjects ---------------------------------------------------------
    def subject_entries(self, states=None):
        subs = self.load_config().get("subjects") or []
        out = [s for s in subs if isinstance(s, dict) and s.get("id")]
        if states:
            wanted = set([states] if isinstance(states, str) else states)
            out = [s for s in out if s.get("state", "live") in wanted]
        return out

    def subject_entry(self, sid):
        for s in self.subject_entries():
            if s.get("id") == sid:
                return s
        return None

    def subject_ids(self, states=None):
        return [s["id"] for s in self.subject_entries(states)]

    def live_subject_ids(self):
        return self.subject_ids("live")

    def subject(self, sid):
        entry = self.subject_entry(sid)
        if entry is None:
            known = ", ".join(self.subject_ids()) or "none yet"
            raise UsageError("Unknown subject '%s'. Subjects: %s" % (sid, known))
        return Subject(self, entry["id"], entry.get("dir") or entry["id"])

    def subjects(self, states=None):
        return [Subject(self, s["id"], s.get("dir") or s["id"]) for s in self.subject_entries(states)]

    def subject_from_cwd(self, cwd=None):
        here = Path(cwd) if cwd is not None else Path.cwd()
        try:
            rel = here.resolve().relative_to(self.root)
        except (ValueError, OSError):
            return None
        if not rel.parts:
            return None
        first = rel.parts[0]
        for s in self.subject_entries():
            if (s.get("dir") or s["id"]) == first:
                return Subject(self, s["id"], s.get("dir") or s["id"])
        return None

    def resolve_subject(self, arg=None, cwd=None):
        """Subject from an argument, else the cwd, else the only live subject."""
        if arg:
            return self.subject(arg)
        subj = self.subject_from_cwd(cwd)
        if subj is not None:
            return subj
        live = self.live_subject_ids()
        if len(live) == 1:
            return self.subject(live[0])
        if not live:
            raise UsageError(
                "No live subjects yet. Run: indelible.py subject add <id> --title <title> --profile <profile>"
            )
        raise UsageError("Which subject? Pass one of: %s" % ", ".join(live))

    # ---- ledger (append) ---------------------------------------------------
    def load_ledger(self, include_archive=False):
        rows = self.read_jsonl(self.ledger_path)
        if include_archive:
            for p in sorted(self.archive_dir.glob("ledger-*.jsonl")):
                rows = self.read_jsonl(p) + rows
        return rows

    def append_ledger(self, row):
        return fio.append_jsonl(self.ledger_path, row)

    def ledger_status(self, rows=None):
        """ref -> latest status event row (the latest ``status`` event wins)."""
        rows = self.load_ledger() if rows is None else rows
        out = {}
        for r in rows:
            if r.get("kind") == "status" and r.get("ref"):
                out[r["ref"]] = r
        return out

    def open_ledger_items(self, kind=None, subject=None, rows=None):
        """Ledger items (not status events) whose latest status is open or none."""
        rows = self.load_ledger() if rows is None else rows
        status = self.ledger_status(rows)
        out = []
        for r in rows:
            if r.get("kind") == "status" or not r.get("id"):
                continue
            if kind and r.get("kind") != kind:
                continue
            if subject and r.get("subject") not in (subject, None):
                continue
            st = status.get(r["id"])
            if st and st.get("status") not in (None, "open"):
                continue
            out.append(r)
        return out

    def next_ledger_id(self):
        ids = _ids_in(self.load_ledger(include_archive=True), "id", "ref")
        return "L-%04d" % (max_seq(ids, r"^L-(\d+)$") + 1)

    # ---- plan blocks (snapshot) --------------------------------------------
    def load_blocks(self, include_archive=False):
        rows = self.read_jsonl(self.blocks_path)
        if include_archive:
            for p in sorted((self.plan_dir / "archive").glob("*.jsonl")):
                rows = self.read_jsonl(p) + rows
        return rows

    def save_blocks(self, rows):
        return fio.write_jsonl(self.blocks_path, rows)

    def get_block(self, block_id):
        for b in self.load_blocks():
            if b.get("id") == block_id:
                return b
        return None

    def next_block_id(self, subject_id, day, taken=None):
        """``B-YYYYMMDD-<subject>-N`` for the given date (N = 1 + max seen)."""
        from lib import dates
        stamp = dates.to_date(day).strftime("%Y%m%d")
        ids = _ids_in(self.load_blocks(include_archive=True), "id", "pair")
        ids += list(taken or [])
        rx = r"^B-%s-%s-(\d+)$" % (stamp, re.escape(subject_id))
        return "B-%s-%s-%d" % (stamp, subject_id, max_seq(ids, rx) + 1)

    # ---- render state ------------------------------------------------------
    def load_render_state(self):
        return fio.read_json(self.render_state_path, default={}) or {}

    def save_render_state(self, data):
        return fio.write_json(self.render_state_path, data)



"""The learner's workspace: discovery, paths, config, subjects and data files.

Discovery order:
  1. the ``--workspace PATH`` flag;
  2. the environment variable ``INDELIBLE_WORKSPACE``;
  3. walking up from the current folder (at most 4 levels) for ``indelible.json``;
  4. the path stored in ``~/.indelible/workspace``.

A flag or environment path must name the workspace root itself (the folder
holding ``indelible.json``); it is never walked up from.

Usage in a command handler::

    from lib import ws as wsmod
    ws = wsmod.from_args(args)             # raises NoWorkspace (exit 2)
    subj = ws.resolve_subject(args.subject)
    with ws.lock():
        errors = subj.load_errors()
        ...
        subj.save_errors(errors)
"""

import os
import re
from pathlib import Path

from lib import NoWorkspace, UsageError, DataError, WORKSPACE_ASSETS
from lib import io as fio

MAX_WALK_UP = 4
ENV_WORKSPACE = "INDELIBLE_WORKSPACE"
CONFIG_NAME = "indelible.json"
MARK_BEGIN = "<!-- indelible:begin -->"
MARK_END = "<!-- indelible:end -->"
GENERATED_BANNER = "<!-- generated by indelible; do not edit -->"

SUBJECT_ID_RE = re.compile(r"^[a-z](?:[a-z0-9-]{0,30}[a-z0-9])?$")
RESERVED_SUBJECT_IDS = {
    "all", "root", "plan", "views", "reviews", "inbox", "archive", "data", "notes",
    "sheets", "scans", "answers", "ledger", "indelible", "none",
}

ROOT_DIRS = ["plan", "plan/ics", "views", "reviews", "inbox", ".indelible", ".indelible/backups"]
SUBJECT_DIRS = [
    "data", "views", "notes", "sheets", "scans", "answers", "archive",
    ".indelible", ".indelible/specs", ".indelible/keys", ".indelible/keys/errors", ".indelible/tmp",
]



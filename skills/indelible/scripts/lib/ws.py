def pointer_file():
    """``~/.indelible/workspace`` (honours HOME / USERPROFILE)."""
    return Path(os.path.expanduser("~")) / ".indelible" / "workspace"


def _root_at_or_above(path, max_up=MAX_WALK_UP):
    p = Path(path).expanduser()
    try:
        p = p.resolve()
    except OSError:
        return None
    for _ in range(max_up + 1):
        if (p / CONFIG_NAME).is_file():
            return p
        if p.parent == p:
            break
        p = p.parent
    return None


def read_pointer(pointer=None):
    pf = Path(pointer) if pointer is not None else pointer_file()
    try:
        text = fio.read_text(pf)
    except OSError:
        return None
    if not text:
        return None
    for line in text.split("\n"):
        if line.strip():
            return Path(line.strip()).expanduser()
    return None


def discover(flag=None, environ=None, cwd=None, pointer=None):
    """Find the workspace root. Returns ``(path or None, source, detail)``.

    ``source`` is one of ``flag``, ``env``, ``cwd``, ``pointer`` or ``none``.
    An explicit flag or environment path that holds no workspace is not
    passed over: it returns ``(None, "flag"|"env", detail)``.
    """
    if flag:
        root = _root_at_or_above(flag, max_up=0)
        if root:
            return root, "flag", str(flag)
        return None, "flag", "--workspace %s holds no indelible.json" % flag
    if environ is None:
        env_path = os.environ.get("INDELIBLE_WORKSPACE")
    else:
        env_path = environ.get(ENV_WORKSPACE)
    if env_path:
        root = _root_at_or_above(env_path, max_up=0)
        if root:
            return root, "env", env_path
        return None, "env", "%s=%s holds no indelible.json" % (ENV_WORKSPACE, env_path)
    start = Path(cwd) if cwd is not None else Path.cwd()
    root = _root_at_or_above(start, MAX_WALK_UP)
    if root:
        return root, "cwd", str(start)
    ptr = read_pointer(pointer)
    if ptr is not None and (ptr / CONFIG_NAME).is_file():
        return ptr.resolve(), "pointer", str(ptr)
    return None, "none", None


def find_workspace(flag=None, environ=None, cwd=None, pointer=None):
    """The workspace root Path, or None."""
    return discover(flag, environ, cwd, pointer)[0]


def open_workspace(flag=None, required=True):
    root, source, detail = discover(flag)
    if root is None:
        if required:
            raise NoWorkspace(detail if source in ("flag", "env") else None)
        return None
    return Workspace(root)


def from_args(args, required=True):
    """The Workspace for a parsed argparse namespace (uses ``args.workspace``)."""
    return open_workspace(getattr(args, "workspace", None), required=required)


require = from_args



def replace_marked_section(text, inner):
    """Replace what lies between the begin/end markers (appending them if absent)."""
    inner = inner.rstrip("\n")
    b, e = text.find(MARK_BEGIN), text.find(MARK_END)
    if b == -1 or e == -1 or e < b:
        sep = "" if text.endswith("\n") or not text else "\n"
        return text + sep + MARK_BEGIN + "\n" + inner + "\n" + MARK_END + "\n"
    return text[: b + len(MARK_BEGIN)] + "\n" + inner + "\n" + text[e:]


def marked_section(text):
    """What lies between the markers, or None."""
    b, e = text.find(MARK_BEGIN), text.find(MARK_END)
    if b == -1 or e == -1 or e < b:
        return None
    return text[b + len(MARK_BEGIN): e].strip("\n")



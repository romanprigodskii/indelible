def asset_text(name):
    """Text of a file in ``assets/workspace/``."""
    text = fio.read_text(WORKSPACE_ASSETS / name)
    if text is None:
        raise DataError("Missing skill asset: assets/workspace/%s" % name)
    return text


def default_config():
    import json
    return json.loads(asset_text("indelible.json"))


def default_subject():
    import json
    return json.loads(asset_text("subject.json"))


def root_subjects_section(ws):
    """The generated lines of the root CLAUDE.md: live subjects only."""
    lines = []
    for s in ws.subject_entries("live"):
        sid = s["id"]
        title, profile = sid, ""
        try:
            cfg = Subject(ws, sid, s.get("dir") or sid).load()
            title = cfg.get("title") or sid
            profile = cfg.get("profile") or ""
        except DataError:
            pass
        extra = " (%s)" % profile if profile else ""
        lines.append('- `%s`: %s%s. Folder `%s/`. Say "start %s".' % (
            sid, title, extra, s.get("dir") or sid, sid))
    if not lines:
        lines.append("(no live subjects yet)")
    return "\n".join(lines)


def update_root_claude_md(ws):
    """Rewrite the generated section of the root CLAUDE.md (if the file exists)."""
    path = ws.claude_md
    text = fio.read_text(path)
    if text is None:
        return False
    new = replace_marked_section(text, root_subjects_section(ws))
    if new != text:
        fio.write_text(path, new, backup=False)
        return True
    return False

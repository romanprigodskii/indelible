def max_seq(ids, pattern):
    """Largest integer captured by ``pattern`` (group 1) among ids; 0 if none."""
    rx = re.compile(pattern) if isinstance(pattern, str) else pattern
    best = 0
    for i in ids:
        if not isinstance(i, str):
            continue
        m = rx.match(i)
        if m:
            best = max(best, int(m.group(1)))
    return best


def _ids_in(rows, *fields):
    out = []
    for r in rows:
        for f in fields:
            v = r.get(f)
            if isinstance(v, str):
                out.append(v)
    return out



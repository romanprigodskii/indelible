class Subject(object):
    """One subject folder inside the workspace."""

    def __init__(self, ws, sid, dirname=None):
        self.ws = ws
        self.id = sid
        self.dirname = dirname or sid
        self.root = ws.root / self.dirname
        self._cfg = None

    def __repr__(self):
        return "Subject(%r)" % self.id

    # ---- paths ------------------------------------------------------------
    json_path = property(lambda self: self.root / "subject.json")
    claude_md = property(lambda self: self.root / "CLAUDE.md")
    data_dir = property(lambda self: self.root / "data")
    sessions_path = property(lambda self: self.data_dir / "sessions.jsonl")
    attempts_path = property(lambda self: self.data_dir / "attempts.jsonl")
    exposures_path = property(lambda self: self.data_dir / "exposures.jsonl")
    errors_path = property(lambda self: self.data_dir / "errors.jsonl")
    sheets_path = property(lambda self: self.data_dir / "sheets.jsonl")
    topics_path = property(lambda self: self.data_dir / "topics.json")
    glossary_path = property(lambda self: self.data_dir / "glossary.jsonl")
    views_dir = property(lambda self: self.root / "views")
    notes_dir = property(lambda self: self.root / "notes")
    sheets_dir = property(lambda self: self.root / "sheets")
    scans_dir = property(lambda self: self.root / "scans")
    scans_index_path = property(lambda self: self.root / "scans" / "index.jsonl")
    answers_dir = property(lambda self: self.root / "answers")
    archive_dir = property(lambda self: self.root / "archive")
    state_dir = property(lambda self: self.root / ".indelible")
    session_lock_path = property(lambda self: self.state_dir / "session.lock")
    unclosed_path = property(lambda self: self.state_dir / "unclosed")
    specs_dir = property(lambda self: self.state_dir / "specs")
    keys_dir = property(lambda self: self.state_dir / "keys")
    key_errors_dir = property(lambda self: self.state_dir / "keys" / "errors")
    keys_opened_path = property(lambda self: self.state_dir / "keys" / "opened.jsonl")
    tmp_dir = property(lambda self: self.state_dir / "tmp")

    def spec_path(self, sheet_id):
        """The sealed visible spec: ``.indelible/specs/<id>.json``."""
        return self.specs_dir / ("%s.json" % sheet_id)

    def tmp_spec_path(self, sheet_id):
        """Where the builder writes a spec: ``.indelible/tmp/<id>.spec.json``."""
        return self.tmp_dir / ("%s.spec.json" % sheet_id)

    def tmp_answers_path(self, sheet_id):
        """Where the builder writes answers: ``.indelible/tmp/<id>.answers.json``."""
        return self.tmp_dir / ("%s.answers.json" % sheet_id)

    def typed_answers_path(self, sheet_id):
        """The learner's typed answers: ``answers/<id>.txt``."""
        return self.answers_dir / ("%s.txt" % sheet_id)

    def view_path(self, name):
        """``views/<name>`` (e.g. brief.md, progress.md, errors.md, log.md)."""
        return self.views_dir / name

    def notes_path(self, name):
        """``notes/<name>.md`` (append-only)."""
        return self.notes_dir / ("%s.md" % name)

    def key_path(self, sheet_id):
        return self.keys_dir / ("%s.json" % sheet_id)

    def error_key_path(self, error_id):
        return self.key_errors_dir / ("%s.json" % error_id)

    def sheet_month_dir(self, day):
        from lib import dates
        return self.sheets_dir / dates.to_date(day).strftime("%Y-%m")

    def rel(self, path):
        return self.ws.rel(path)

    def ensure_tree(self):
        for d in SUBJECT_DIRS:
            fio.ensure_dir(self.root / d)
        try:
            os.chmod(str(self.keys_dir), 0o700)
        except OSError:
            pass

    # ---- subject.json -------------------------------------------------------
    def load(self, reload=False):
        if self._cfg is None or reload:
            cfg = fio.read_json(self.json_path)
            if not isinstance(cfg, dict):
                raise DataError("%s is missing or not a JSON object" % self.json_path)
            self._cfg = cfg
        return self._cfg

    config = property(lambda self: self.load())

    def save(self, cfg):
        fio.write_json(self.json_path, cfg)
        self._cfg = cfg

    def title(self):
        return self.load().get("title") or self.id

    def profile(self):
        return self.load().get("profile")

    def target_date(self):
        from lib import dates
        d = (self.load().get("target") or {}).get("date")
        try:
            return dates.to_date(d) if d else None
        except ValueError:
            return None

    deadline = target_date

    def cold_window(self):
        w = self.load().get("cold_window_h") or [44, 72]
        try:
            return float(w[0]), float(w[1])
        except (TypeError, ValueError, IndexError):
            return 44.0, 72.0

    def topics(self):
        return [t for t in (self.load().get("topics") or []) if isinstance(t, dict) and t.get("id")]

    def topic(self, tid):
        for t in self.topics():
            if t["id"] == tid:
                return t
        return None

    def topic_ids(self):
        return [t["id"] for t in self.topics()]

    def require_topic(self, tid):
        t = self.topic(tid)
        if t is None:
            known = ", ".join(self.topic_ids()) or "none yet"
            raise UsageError("Unknown topic '%s' in %s. Topics: %s" % (tid, self.id, known))
        return t

    # ---- append files --------------------------------------------------------
    def load_sessions(self, include_archive=False):
        rows = self.ws.read_jsonl(self.sessions_path)
        if include_archive:
            for p in sorted(self.archive_dir.glob("sessions-*.jsonl")):
                rows = self.ws.read_jsonl(p) + rows
        return rows

    def append_session(self, row):
        return fio.append_jsonl(self.sessions_path, row)

    def load_attempts(self, include_archive=False):
        rows = []
        if include_archive:
            for p in sorted(self.archive_dir.glob("attempts-*.jsonl")):
                rows.extend(self.ws.read_jsonl(p))
        rows.extend(self.ws.read_jsonl(self.attempts_path))
        return rows

    def append_attempt(self, row):
        return fio.append_jsonl(self.attempts_path, row)

    def load_exposures(self):
        return self.ws.read_jsonl(self.exposures_path)

    def append_exposure(self, row):
        return fio.append_jsonl(self.exposures_path, row)

    def load_scan_index(self):
        return self.ws.read_jsonl(self.scans_index_path)

    def append_scan_index(self, row):
        return fio.append_jsonl(self.scans_index_path, row)

    def load_keys_opened(self):
        return self.ws.read_jsonl(self.keys_opened_path)

    def append_key_opened(self, row):
        return fio.append_jsonl(self.keys_opened_path, row)

    # ---- snapshot files --------------------------------------------------------
    def load_errors(self, include_archive=False):
        rows = []
        if include_archive:
            for p in sorted(self.archive_dir.glob("errors-*.jsonl")):
                rows.extend(self.ws.read_jsonl(p))
        rows.extend(self.ws.read_jsonl(self.errors_path))
        return rows

    def save_errors(self, rows):
        return fio.write_jsonl(self.errors_path, rows)

    def get_error(self, error_id):
        for e in self.load_errors():
            if e.get("id") == error_id:
                return e
        return None

    def load_sheets(self):
        return self.ws.read_jsonl(self.sheets_path)

    def save_sheets(self, rows):
        return fio.write_jsonl(self.sheets_path, rows)

    def get_sheet(self, sheet_id):
        for s in self.load_sheets():
            if s.get("id") == sheet_id:
                return s
        return None

    def upsert_sheet(self, row):
        """Replace the sheets row with the same id, or append it. Saves."""
        rows = self.load_sheets()
        for i, s in enumerate(rows):
            if s.get("id") == row.get("id"):
                rows[i] = row
                break
        else:
            rows.append(row)
        self.save_sheets(rows)
        return row

    def load_topics_state(self):
        data = fio.read_json(self.topics_path, default={})
        return data if isinstance(data, dict) else {}

    def save_topics_state(self, data):
        return fio.write_json(self.topics_path, data)

    def load_glossary(self):
        return self.ws.read_jsonl(self.glossary_path)

    def save_glossary(self, rows):
        return fio.write_jsonl(self.glossary_path, rows)

    # ---- session lock ----------------------------------------------------------
    def read_session_lock(self):
        if not self.session_lock_path.exists():
            return None
        try:
            data = fio.read_json(self.session_lock_path)
        except DataError:
            return {}
        return data if isinstance(data, dict) else {}

    def write_session_lock(self, data):
        return fio.write_json(self.session_lock_path, data, backup=False)

    def remove_session_lock(self):
        for p in (self.session_lock_path, self.unclosed_path):
            try:
                p.unlink()
            except OSError:
                pass

    def is_parked(self):
        return self.unclosed_path.exists()

    # ---- IDs ------------------------------------------------------------------
    def next_error_id(self, taken=None):
        """``E-<subject>-NNNN``: 1 + the max seen in errors, attempts and archive."""
        ids = _ids_in(self.load_errors(include_archive=True), "id")
        ids += _ids_in(self.load_attempts(include_archive=True), "error_id")
        if self.key_errors_dir.exists():
            ids += [p.stem for p in self.key_errors_dir.glob("E-*.json")]
        ids += list(taken or [])
        rx = r"^E-%s-(\d+)$" % re.escape(self.id)
        return "E-%s-%04d" % (self.id, max_seq(ids, rx) + 1)

    def next_session_id(self, taken=None):
        """``S-<subject>-NNNN``: 1 + the max seen in sessions, archive and the open lock."""
        ids = _ids_in(self.load_sessions(include_archive=True), "id")
        lock = self.read_session_lock() or {}
        if lock.get("session_id"):
            ids.append(lock["session_id"])
        ids += list(taken or [])
        rx = r"^S-%s-(\d+)$" % re.escape(self.id)
        return "S-%s-%04d" % (self.id, max_seq(ids, rx) + 1)


